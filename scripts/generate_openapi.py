#!/usr/bin/env python3
"""Generate or check deterministic public OpenAPI and endpoint artifacts."""
from __future__ import annotations

import argparse
import json
from pathlib import Path
from api_contract import build
from skill_openapi import generated as skill_artifacts

ROOT = Path(__file__).resolve().parents[1]


def pricing_table(pricing):
    from decimal import Decimal
    if not pricing["rules"] and not pricing["plans"]:
        return "No verified public rates or plan amounts are included. Confirm the current published account price in the Sawalni portal."
    rows = ["| Rule | USD rate and unit |", "|---|---|"]
    for rule in pricing["rules"]:
        name = ", ".join(f"{key}={value}" for key, value in rule["match"].items())
        terms = []
        for metric, value in rule["usd_per_million_units"].items():
            scale, unit = {
                "audio_seconds": (60, "audio minute"), "billable_blocks": (1000, "1,000 blocks"),
                "operations": (1000, "1,000 operations"), "requests": (1000, "1,000 requests"),
                "pages": (1000, "1,000 pages"), "completed_runs": (1, "completed run"),
            }.get(metric, (1000000, "1M " + metric))
            price = Decimal(value) * scale / 1000000
            terms.append(f"${price.quantize(Decimal('0.00000001')).normalize():f} / {unit}")
        terms = "; ".join(terms)
        rows.append(f"| {name} | {terms or 'Zero compute price; access rules still apply'} |")
    rows += ["", "Audio meters emit seconds; displayed audio rates use minutes.",
             "Block and operation meters count each block or operation as one base unit.", "",
             "| Plan | Monthly USD | Included allowances |", "|---|---|---|"]
    for name, plan in pricing["plans"].items():
        allowances = "; ".join(f"{key}: {value}" for key, value in plan.items() if key != "monthly_usd")
        rows.append(f"| {name} | ${plan['monthly_usd']} | {allowances} |")
    return "\n".join(rows)


def artifacts():
    spec = build()
    rows = ["# Hosted API endpoints", "", "Generated from the reviewed OpenAPI definitions. Do not edit this list.", "",
            "Read `api/openapi.json` at the repository root for schemas and examples.", "",
            "| Method | Path | Purpose |", "|---|---|---|"]
    for path, methods in sorted(spec["paths"].items()):
        for method, operation in sorted(methods.items()):
            rows.append(f"| {method.upper()} | `{path}` | {operation['summary']} |")
    rows += ["", "WebSocket: `wss://api.sawalni.com/v1/speech/transcribe/stream`.",
             "Read `transcription.md` for the session protocol.", ""]
    artifacts = {ROOT / "api/openapi.json": json.dumps(spec, ensure_ascii=False, indent=2) + "\n",
                 ROOT / "skills/omneity/references/endpoints.md": "\n".join(rows)}
    artifacts.update(skill_artifacts(spec))
    pricing = json.loads((ROOT / "api/pricing.json").read_text())
    artifacts[ROOT / "skills/omneity/references/pricing-rates.md"] = (
        "# Public pricing status\n\nDo not edit this file. Regenerate it from `api/pricing.json`.\n\n"
        + f"Currency: {pricing['currency']}.\n\n"
        + "Read `pricing.md` before quoting costs.\n\n"
        + pricing_table(pricing) + "\n")
    return artifacts


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail when committed artifacts need regeneration")
    args = parser.parse_args()
    failed = []
    for path, text in artifacts().items():
        if args.check:
            if not path.exists() or path.read_text() != text:
                failed.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    if failed:
        print("Stale generated artifacts: " + ", ".join(failed))
        return 1
    print("OpenAPI artifacts " + ("are current." if args.check else "generated."))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
